def expand_franchise_titles(keywords: list[str]) -> list[str]:
    """keywords에 프랜차이즈 표현이 있으면 대표 작품 제목 목록을 돌려준다.

    부분일치(substring)라 "슈퍼히어로"도 "히어로" 트리거에 걸린다.
    매칭이 없으면 빈 리스트 — 호출부는 기존 태그 검색만 수행하면 된다.
    """
    titles: list[str] = []
    seen: set[str] = set()
    for kw in keywords:
        for trigger, expansion in _FRANCHISE_TO_TITLES.items():
            if trigger in kw:
                for t in expansion:
                    if t not in seen:
                        seen.add(t)
                        titles.append(t)
    return titles

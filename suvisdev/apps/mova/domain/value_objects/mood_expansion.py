def expand_mood_keywords(keywords: list[str]) -> list[str]:
    """keywords에 mood 표현이 있으면 대중 장르 태그를 뒤에 확장.

    - 부분일치(substring)로 "오싹오싹한"도 "오싹" 트리거에 걸린다.
    - 확장된 장르는 _POPULAR_GENRES 화이트리스트만 통과.
    - 중복은 대소문자 무시 seen set으로 제거.
    """
    expanded = list(keywords)
    seen = {k.lower() for k in keywords}
    for kw in keywords:
        for trigger, genres in _MOOD_TO_GENRES.items():
            if trigger in kw:
                for g in genres:
                    if g in _POPULAR_GENRES and g.lower() not in seen:
                        expanded.append(g)
                        seen.add(g.lower())
    return expanded
